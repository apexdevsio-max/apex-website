import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import test from "node:test";

/**
 * Guards for patterns the audit removed. These read source because the patterns
 * are what is being banned; behaviour is covered by the other test files and by
 * scripts/smoke.mjs against a real build.
 */
const root = process.cwd();

function files(dir, ext = /\.(tsx?|css)$/) {
  const out = [];
  for (const name of readdirSync(path.join(root, dir))) {
    const rel = path.join(dir, name);
    if (statSync(path.join(root, rel)).isDirectory()) out.push(...files(rel, ext));
    else if (ext.test(name)) out.push(rel);
  }
  return out;
}

const source = [...files("app"), ...files("components"), ...files("lib")].map((file) => ({ file, text: readFileSync(path.join(root, file), "utf8") }));
const tsx = source.filter((s) => s.file.endsWith(".tsx"));
const css = readFileSync(path.join(root, "app", "globals.css"), "utf8");

test("every apex-* class used in markup is defined in the stylesheet", () => {
  const used = new Set(tsx.flatMap(({ text }) => [...text.matchAll(/\bapex-[a-z0-9-]+/g)].map((m) => m[0])));
  // Theme-colour utilities generated by Tailwind from @theme, plus the custom event name.
  const generated = /^apex-(bg|card|text|muted|primary|accent|brand|border|control|gold|danger|success)$|^apex-theme-change$/;
  for (const name of used) {
    if (generated.test(name)) continue;
    assert.ok(css.includes(`.${name}`), `.${name} is used but not defined in app/globals.css`);
  }
});

test("RTL is not reversed by hand on top of dir=rtl", () => {
  // The social card is drawn by Satori, which has no bidi support, so it lays
  // Arabic out by hand on purpose.
  for (const { file, text } of tsx.filter((s) => !s.file.endsWith("og-card.tsx"))) {
    assert.doesNotMatch(text, /isAr\s*\?\s*["'`][^"'`]*row-reverse/, `${file} reverses flex direction for Arabic; dir="rtl" already does`);
    assert.doesNotMatch(text, /flexDirection:\s*isAr/, `${file} reverses flex direction for Arabic`);
  }
  assert.doesNotMatch(css, /\[dir="rtl"\]\s*\.lucide/, "every lucide icon must not be mirrored");
});

test("no emoji are used as icons or illustrations", () => {
  // © and ™ are pictographic in Unicode but are not emoji.
  const emoji = /(?![©®™])\p{Extended_Pictographic}/u;
  for (const { file, text } of tsx) {
    const line = text.split("\n").find((l) => emoji.test(l) && !l.trim().startsWith("//") && !l.trim().startsWith("*"));
    assert.equal(line, undefined, `${file} renders an emoji: ${line?.trim()}`);
  }
});

test("buttons on a primary fill take their text colour from the token", () => {
  for (const { file, text } of tsx) {
    assert.doesNotMatch(text, /apex-btn-primary[^"]*text-white/, `${file} hard-codes white text on a primary button`);
  }
});

test("mock data never reaches production code", () => {
  for (const { file, text } of source) assert.doesNotMatch(text, /lib\/mock\//, `${file} imports mock data`);
});

test("analytics are only queued with the Arguments object gtag.js understands", () => {
  const consent = readFileSync(path.join(root, "components", "analytics", "AnalyticsConsent.tsx"), "utf8");
  assert.match(consent, /dataLayer!?\.push\(arguments\)/);
  assert.doesNotMatch(consent, /=>\s*window\.dataLayer\?\.push\(args\)/);
});

test("the footer is never size-contained", () => {
  const footer = readFileSync(path.join(root, "components", "layout", "Footer.tsx"), "utf8");
  assert.doesNotMatch(footer, /contain:\s*["'][^"']*size/);
});
